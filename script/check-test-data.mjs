import { execFileSync } from 'node:child_process'

// Inspect Git's index, so ignored local files and their contents are never read.
const paths = execFileSync('git', ['ls-files', '-z'], { encoding: 'utf8' }).split('\0').filter(Boolean)
const rejected = []
for (const path of paths) {
  // Published game cards are versioned assets, even though their directory is named output.
  // Keep this exception limited to the map data, three card catalogs and numbered PNGs.
  const publishedCardAsset = path === 'game-service/node-types.csv'
    || /^game-service\/content\/(?:hand|events|misfortunes)\.csv$/.test(path)
    || /^game-service\/content\/output\/(?:card|event|mis)[1-9][0-9]*\.png$/.test(path)
  if (publishedCardAsset) continue
  const localArtifact = /(^|\/)(ref|output|tmp|\.local-data|test-results|playwright-report|blob-report|coverage|uploads|backups?|dumps?)(\/|$)/i.test(path)
  const databaseFile = /\.(sql\.(gz|zip)|sqlite3?|db|har|log|dump|csv|tsv)$/i.test(path) || /(^|\/)(CDMGA|database|backup|dump)[^/]*\.sql$/i.test(path)
  const credentials = /(^|\/)(\.env($|\.)|application-local\.properties$|db-password$|account-password$|storage-?state[^/]*\.json$)/i.test(path)
  if (localArtifact || databaseFile || credentials) {
    rejected.push(path)
    continue
  }
  if (path.endsWith('.sql')) {
    const source = execFileSync('git', ['show', `:${path}`], { encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 })
    // Keep schema/migration SQL; user rows must be generated by the fixture code.
    if (/\b(?:INSERT(?:\s+IGNORE)?|REPLACE)\s+INTO\s+`?(?:identity|profile|score|forum_post|forum_reply|identity_extra_profile)`?\s*(?:\([^;]*?\))?\s*VALUES\b/is.test(source)) {
      rejected.push(path)
    }
  }
}
if (rejected.length) {
  console.error('Refusing tracked local data or user-row dumps:\n' + rejected.map(path => `  ${path}`).join('\n'))
  process.exitCode = 1
} else {
  console.log(`Data boundary check passed (${paths.length} indexed paths). No local artifacts or literal user-row SQL dumps found.`)
}
