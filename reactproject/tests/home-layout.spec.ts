import { test, expect } from '@playwright/test'

test('desktop home disc overflows top/bottom and has 8 inner dots', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 720 })
  await page.goto('http://localhost:5174/home')
  await expect(page.locator('.disc-orbit')).toBeVisible()
  await expect(page.locator('.disc-orbit .disc-dot')).toHaveCount(8)
  const firstDot = page.locator('.disc-orbit .disc-dot').first()
  const cx = Number(await firstDot.getAttribute('cx'))
  const cy = Number(await firstDot.getAttribute('cy'))
  expect(Math.abs(cx - 50)).toBeGreaterThan(1)
  expect(cy).toBeLessThan(50)
  await expect(page.locator('.ring')).toHaveCount(0)
  await expect(page.locator('.progress, .dots')).toHaveCount(0)
  await expect(page.locator('.home-details .detail-card')).toHaveCount(4)
  const order = await page.evaluate(() => [...document.querySelectorAll('.side.right .card')].map((el) => el.id))
  expect(order.indexOf('today')).toBeGreaterThan(order.indexOf('member'))
  expect(order.indexOf('today')).toBeLessThan(order.indexOf('forum'))
  await expect(page.locator('#courses, #activities')).toHaveCount(0)
  await expect(page.locator('.site-top')).toBeVisible()
  await expect(page.locator('.side.right #member')).toBeVisible()
  await expect(page.locator('.scrim')).toHaveCount(0)
  const box = await page.locator('.disc').boundingBox()
  expect(box).not.toBeNull()
  expect(box!.y).toBeLessThan(0)
  expect(box!.y + box!.height).toBeGreaterThan(720)
  const height = await page.evaluate(() => document.body.scrollHeight)
  expect(height).toBeGreaterThan(720)
})

test('mobile home disc sticks to both edges', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('http://localhost:5174/home')
  await expect(page.locator('.disc-orbit .disc-dot')).toHaveCount(8)
  const box = await page.locator('.disc').boundingBox()
  expect(box).not.toBeNull()
  expect(Math.abs(box!.x)).toBeLessThan(2)
  expect(Math.abs(box!.width - 390)).toBeLessThan(2)
})
