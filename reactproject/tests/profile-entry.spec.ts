import { test, expect } from '@playwright/test'

test('own profile exposes edit/title entries and titles', async ({ page }) => {
  await page.route('**/api/profile/identity/1', (route) => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ code: 0, data: { id: 1, account: 'tester', description: '签名', status: 1 } }) }))
  await page.route('**/api/identity/online/1', (route) => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ code: 0, data: true }) }))
  await page.route('**/api/score/user-course-scores*', (route) => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ code: 0, data: [{ id: 1, course: { title: '始与终专题' }, score: 10, isScored: true }] }) }))
  await page.route('**/title/mine*', (route) => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ code: 0, data: [{ id: 1, name: '测试称号', tier: 'color', status: 'approved' }] }) }))
  await page.goto('http://localhost:5174/login')
  await page.getByPlaceholder('请输入用户名').fill('tester')
  await page.getByPlaceholder('请输入密码').fill('test123456')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.waitForURL('**/home', { timeout: 20_000 })
  await page.goto('http://localhost:5174/profile/1')
  await expect(page.getByRole('link', { name: '编辑资料', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: '申请称号', exact: true }).first()).toBeVisible()
  const titleBadge = page.locator('.profile-title.color').filter({ hasText: '测试称号' })
  await expect(titleBadge).toBeVisible()
  await expect(titleBadge).toHaveCSS('animation-name', 'title-shimmer')
  await expect(titleBadge).toHaveCSS('background-size', '300% 100%')
  await page.getByRole('link', { name: '编辑资料', exact: true }).click()
  await expect(page).toHaveURL(/profile-setting/)
  await expect(page.getByText('编辑个人信息', { exact: true })).toBeVisible()
})
