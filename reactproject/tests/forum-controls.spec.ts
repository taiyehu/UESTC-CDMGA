import { test, expect } from '@playwright/test'

test('forum sort, like, report and image picker are wired', async ({ page }) => {
  await page.route('**/forum/post/1/like*', (route) => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ code: 0, message: 'ok', data: { liked: true } }) }))
  await page.goto('http://localhost:5174/login')
  await page.getByPlaceholder('请输入用户名').fill('tester')
  await page.getByPlaceholder('请输入密码').fill('test123456')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.waitForURL('**/home', { timeout: 20_000 })
  await page.goto('http://localhost:5174/forum')
  await expect(page.getByRole('button', { name: '全部动态', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '我的帖子', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '最新', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '最多点赞', exact: true })).toBeVisible()
  await expect(page.getByText(/今日曲目推荐推荐/) ).toBeVisible()
  await expect(page.getByRole('button', { name: '举报', exact: true }).first()).toBeVisible()
  const like = page.locator('.forum-actions button').first()
  await expect(like).toBeVisible()
  await like.click()
  await expect(page.locator('.forum-actions button').first()).toContainText('1 点赞')
  await page.getByRole('button', { name: '发帖', exact: true }).click()
  await expect(page.locator('input[type="file"][accept="image/*"]')).toHaveCount(1)
  const attach = page.locator('.forum-upload input[type="file"]').last()
  await attach.setInputFiles({ name: 'note.txt', mimeType: 'text/plain', buffer: Buffer.from('hello') })
  await expect(page.getByText('已选择 1 个附件', { exact: true })).toBeVisible()
})

